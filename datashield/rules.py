def _add_requirement(
    requirements,
    *,
    key,
    title,
    description,
    action,
    priority,
    question,
    gdpr_applicable,
    ru_article=None,
    gdpr_article=None,
):
    """Добавить требование с нормами только для действительно применимых режимов."""
    if ru_article is None and not gdpr_applicable:
        return

    use_gdpr = gdpr_applicable and gdpr_article is not None
    if ru_article is not None and use_gdpr:
        regime = "152-ФЗ + GDPR"
        law = f"152-ФЗ, {ru_article}; GDPR, {gdpr_article}"
        legal_url = RU_LAW_URL
    elif ru_article is not None:
        regime = "152-ФЗ"
        law = f"152-ФЗ, {ru_article}"
        legal_url = RU_LAW_URL
    else:
        regime = "GDPR"
        law = f"GDPR, {gdpr_article}"
        legal_url = GDPR_LAW_URL

    requirement = {
        "key": key,
        "title": title,
        "description": description,
        "law": law,
        "legal_url": legal_url,
        "regime": regime,
        "priority": priority,
        "action": action,
        "question": question,
    }
    if regime == "152-ФЗ + GDPR":
        requirement["legal_urls"] = {
            "152-ФЗ": RU_LAW_URL,
            "GDPR": GDPR_LAW_URL,
        }
    requirements.append(requirement)


