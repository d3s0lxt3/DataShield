def get_document(key, company):
    builders = {
        "privacy_policy": _privacy_policy,
        "consent": _consent,
        "responsible_order": _responsible_order,
        "processing_register": _processing_register,
        "incident_procedure": _incident_procedure,
    }
    try:
        builder = builders[key]
    except KeyError:
        raise KeyError(f"Неизвестный документ: {key}") from None

    metadata = next(item for item in DOCUMENTS if item["key"] == key)
    return {
        "title": metadata["title"],
        "subtitle": _DRAFT_NOTICE,
        "blocks": builder(company),
    }


def _set_font(style, size, bold=False):
    style.font.name = "Times New Roman"
    style.font.size = Pt(size)
    style.font.bold = bold
    style.font.color.rgb = RGBColor(0, 0, 0)
    fonts = style.element.rPr.rFonts
    for attribute in ("ascii", "hAnsi", "eastAsia", "cs"):
        fonts.set(qn(f"w:{attribute}"), "Times New Roman")


def _add_page_number(paragraph):
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = paragraph.add_run("Страница ")
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instruction = OxmlElement("w:instrText")
    instruction.set(qn("xml:space"), "preserve")
    instruction.text = " PAGE "
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    run._r.append(begin)
    run._r.append(instruction)
    run._r.append(end)


def build_docx(key, company):
    content = get_document(key, company)
    document = Document()

    section = document.sections[0]
    section.page_width = Cm(21)
    section.page_height = Cm(29.7)
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(2)
    section.right_margin = Cm(1.5)

    _set_font(document.styles["Normal"], 12)
    _set_font(document.styles["Title"], 16, bold=True)
    _set_font(document.styles["Heading 1"], 14, bold=True)
    for style_name in ("List Bullet", "List Number"):
        _set_font(document.styles[style_name], 12)

    normal_format = document.styles["Normal"].paragraph_format
    normal_format.space_after = Pt(6)
    normal_format.line_spacing = 1.15
    document.styles["Heading 1"].paragraph_format.space_before = Pt(12)
    document.styles["Heading 1"].paragraph_format.space_after = Pt(6)

    title = document.add_heading(content["title"], level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle = document.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle_run = subtitle.add_run(content["subtitle"])
    subtitle_run.italic = True

    for block in content["blocks"]:
        block_type = block["type"]
        if block_type == "h":
            document.add_heading(block["text"], level=1)
        elif block_type == "p":
            document.add_paragraph(block["text"])
        elif block_type == "list":
            for item in block["items"]:
                document.add_paragraph(item, style="List Bullet")
        else:
            raise ValueError(f"Неподдерживаемый тип блока: {block_type}")

    _add_page_number(section.footer.paragraphs[0])

    output = BytesIO()
    document.save(output)
    return output.getvalue()


def build_documents_zip(company):
    output = BytesIO()
    with ZipFile(output, mode="w", compression=ZIP_DEFLATED) as archive:
        for metadata in DOCUMENTS:
            archive.writestr(
                metadata["filename"],
                build_docx(metadata["key"], company),
            )
    return output.getvalue()
